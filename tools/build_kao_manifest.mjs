// Shared portrait resource catalog only; never reads game/save/database data.
// Run after intentional resource changes; --check compares without writing.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';

assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'only --check is supported');
const directory = new URL('../web/kao/', import.meta.url);
const files = (await readdir(directory)).filter(file => file.endsWith('.png'));
assert.ok(files.length > 0 && files.every(file => /^(0|[1-9][0-9]*)\.png$/.test(file)), 'canonical numeric portrait filenames required');
files.sort((a, b) => Number(a.slice(0, -4)) - Number(b.slice(0, -4)));
const entries = await Promise.all(files.map(async file => {
  const bytes = await readFile(new URL(file, directory));
  return { id: file.slice(0, -4), file, sha256: createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length };
}));
const output = '// Shared portrait resources: numeric IDs; DOS portraits remain 0..149.\n'
  + '// Generated by tools/build_kao_manifest.mjs; verify with --check.\n'
  + `export const KAO_MANIFEST = [\n${entries.map(entry => '  ' + JSON.stringify(entry)).join(',\n')}\n];\n`;
const target = new URL('manifest.js', directory);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'portrait catalog differs from disk');
else await writeFile(target, output);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} portrait manifest: ${entries.length} numeric assets`);

// Regenerate the fixed chapter-1 native base used by authoring materialize.
// Input is the pinned installed source only (tools/editor_builtin_source.mjs):
// no author-supplied registry, no latest-template fallback, no writes outside
// the one generated module. Chapter 1 is chapterOrder[0] — the same chapter
// copyBuiltinGame reads its game-level constants from.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readInstalledEditorSource } from './editor_builtin_source.mjs';

export const CHAPTER_BASE_OUTPUT = fileURLToPath(new URL('../web/src/content/authoring/chapterbase.generated.js', import.meta.url));

// 武將槽不再是身份（2026-11 用戶裁決）：空白章的 128 槽由 emptyGeneralSlot 產生，
// 所以基座不再保存固定源的武將骨架欄位。
// City slots keep the whole 32-byte record verbatim (unknown bytes must never be
// invented) plus the display name, which is not inside the record.
// Faction slots keep the 22 fixed 64-byte records verbatim for the same reason:
// create-faction reuses the same-slot bytes and only rewrites the fields the
// author owns, so unproven bytes stay original content.
export function buildChapterBase(source) {
  const chapter = source.chapters[0];
  if (!chapter || chapter.state?.cities?.length !== 192 || chapter.state.generals?.length !== 128)
    throw new RangeError('fixed source chapter 1 must carry 192 cities and 128 generals');
  const factionSlots = chapter.state.nativeFactionSlotRaw;
  if (!Array.isArray(factionSlots) || factionSlots.length !== 22)
    throw new RangeError('fixed source chapter 1 must carry the 22-slot native faction source');
  for (const [slot, raw] of factionSlots.entries())
    if (typeof raw !== 'string' || !/^[0-9a-f]{128}$/.test(raw)) throw new RangeError(`faction slot ${slot} needs a 64-byte record`);
  const cities = chapter.state.cities.map((city, slot) => {
    if (city.idx !== slot) throw new RangeError(`city slot order: ${city.idx}`);
    if (typeof city.name !== 'string' || !city.name.trim()) throw new RangeError(`city slot ${slot} needs a name`);
    if (typeof city.raw !== 'string' || !/^[0-9a-f]{64}$/.test(city.raw)) throw new RangeError(`city slot ${slot} needs a 32-byte record`);
    return [city.name, city.raw];
  });
  return { revision: source.revision, chapterId: chapter.id, cities, factionSlots };
}

export function renderChapterBaseModule(base) {
  return `// Generated by tools/build_chapter_base.mjs from the pinned builtin chapter 1\n` +
    `// (${base.revision} / ${base.chapterId}). Never edit by hand: regenerate and re-verify.\n` +
    `function freeze(value) { if (value && typeof value === "object") { for (const child of Object.values(value)) freeze(child); Object.freeze(value); } return value; }\n` +
    `export const CHAPTER_BASE = freeze(${JSON.stringify(base)});\n`;
}

export function readPinnedChapterBase() {
  return buildChapterBase(readInstalledEditorSource());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const text = renderChapterBaseModule(readPinnedChapterBase());
  const current = (() => { try { return readFileSync(CHAPTER_BASE_OUTPUT, 'utf8'); } catch { return null; } })();
  if (check) {
    if (current !== text) throw new Error('chapterbase.generated.js is stale; run node tools/build_chapter_base.mjs');
    process.stdout.write(`${JSON.stringify({ status: 'CHAPTER-BASE-CURRENT', bytes: Buffer.byteLength(text) })}\n`);
  } else {
    writeFileSync(CHAPTER_BASE_OUTPUT, text);
    process.stdout.write(`${JSON.stringify({ status: 'CHAPTER-BASE-WRITTEN', bytes: Buffer.byteLength(text) })}\n`);
  }
}
